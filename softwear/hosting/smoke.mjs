// Public demo checks use only the published fictional accounts.
import assert from 'node:assert/strict';
import { createClient } from '../backend/.deploy/quickback.client.ts';
import { demoAccounts, demoPassword } from './src/demo-data.ts';
const origin = process.env.SOFTWEAR_PUBLIC_ORIGIN ?? 'https://softwear.examples.quickback.dev';
function passed(name) { console.log('PASS ' + name); }
for (const [path, status] of [['/', 200], ['/shop', 200], ['/story', 200], ['/account', 200], ['/account/login', 200], ['/p/challenger-eco-fleece-hoodie', 200], ['/not-a-route', 404], ['/missing-file.js', 404]]) assert.equal((await fetch(origin + path)).status, status, path);
const home = await (await fetch(origin)).text();
for (const value of ['Orders are simulated', 'shopper@softwear.example', 'admin@softwear.example', demoPassword, 'every 30 minutes']) assert.ok(home.includes(value), value);
passed('pages, CMS login, public credentials, reset notice and real 404s');
assert.equal((await (await fetch(origin + '/health')).json()).status, 'ok');
assert.equal((await fetch(origin + '/app.js')).status, 200);
passed('frontend bundle and same-origin backend');
function connection() {
  let token = null;
  return createClient({ baseUrl: origin, auth: 'bearer', headers: { Origin: origin }, sessionStore: { get: () => token, set: (next) => { token = next; } } });
}
const guest = connection();
const [shopper, admin] = [connection(), connection()];
for (const [index, client] of [shopper, admin].entries()) await client.auth.signIn.email({ email: demoAccounts[index].email, password: demoPassword });
passed('published shopper and CMS admin passwords');
const cookieLogin = await fetch(origin + '/auth/v1/sign-in/email', { method: 'POST', headers: { Origin: origin, 'content-type': 'application/json' }, body: JSON.stringify({ email: demoAccounts[1].email, password: demoPassword }) });
assert.equal(cookieLogin.status, 200);
const cookies = cookieLogin.headers.getSetCookie().map((cookie) => cookie.split(';')[0]).join('; ');
assert.ok(cookies.includes('session_token'));
const adminHeaders = { Cookie: cookies, Origin: origin, 'content-type': 'application/json' };
const cms = await fetch(origin + '/cms/', { headers: adminHeaders, redirect: 'manual' });
assert.equal(cms.status, 200);
const cmsHtml = await cms.text();
assert.match(cmsHtml, /__QUICKBACK_RUNTIME/);
assert.match(cmsHtml, /"pinnedOrganizationId":"softwear-demo-store"/);
const runtimeMatch = cmsHtml.match(/window\.__QUICKBACK_RUNTIME\s*=\s*(\{[^<]+?\});?\s*<\/script>/);
assert.ok(runtimeMatch, 'CMS runtime injection');
const navigation = JSON.parse(JSON.parse(runtimeMatch[1]).cmsNavigation);
assert.deepEqual(navigation.map((group) => group.label), ['Catalogue', 'Shopping', 'Orders', 'Marketing']);
assert.equal(new Set(navigation.flatMap((group) => group.tables)).size, 10);
const workspace = await fetch(origin + '/auth/v1/organization/get-full-organization?organizationId=softwear-demo-store', { headers: adminHeaders });
assert.equal(workspace.status, 200);
const workspaceBody = await workspace.json();
assert.equal(workspaceBody.name, 'Softwear demo');
assert.ok(workspaceBody.members.some((member) => member.userId === 'softwear-demo-admin' && member.role === 'owner'));
assert.equal((await fetch(origin + '/api/v1/schema', { headers: adminHeaders })).status, 200);
passed('cookie-based CMS session and schema access');
const products = (await guest.products.list({ limit: 100, sort: 'position,id' })).data;
assert.equal(products.length, 46);
const chosen = products[0];
const editHeaders = { ...adminHeaders, 'If-Match': chosen.modifiedAt };
const updated = await fetch(origin + '/api/v1/products/' + chosen.id, { method: 'PATCH', headers: editHeaders, body: JSON.stringify({ name: chosen.name }) });
assert.equal(updated.status, 200, await updated.text());
assert.ok((await admin.subscribers.list()).data.length >= 1);
assert.ok((await admin.restockRequests.list()).data.length >= 1);
assert.ok((await admin.orders.list()).data.some((order) => order.number === 'SW-DEMO-1001'));
passed('admin product editing and sample orders, subscribers and restock requests');
for (const request of [() => shopper.subscribers.list(), () => guest.orders.list(), () => shopper.products.update(chosen.id, { name: 'Denied' })]) {
  const status = await request().then(() => 200, (error) => error.status);
  assert.ok([401, 403].includes(status), `expected denied, got ${status}`);
}
passed('shopper and guest denied staff operations');
for (const path of ['/auth/v1/change-password', '/auth/v1/admin/set-role', '/auth/v1/delete-user', '/auth/v1/sign-up/email', '/api/v1/operator/users']) assert.equal((await fetch(origin + path, { method: 'POST', headers: adminHeaders, body: '{}' })).status, 403, path);
passed('public admin cannot change credentials, create accounts or administer users');
const stock = (await guest.stock.list({ limit: 100, filter: { productSlug: chosen.slug } })).data.find((row) => row.count > 1);
assert.ok(stock);
await shopper.bagItems.actions.sync({ lines: [{ slug: chosen.slug, color: chosen.colors[0].name, size: stock.size, qty: 1 }] });
const placed = await shopper.orders.actions.checkout({ email: demoAccounts[0].email, name: 'Demo Shopper', address: '1 Example Street', city: 'Example City', zip: '00000', shipping: 'standard' });
assert.equal(placed.subtotalCents, chosen.priceCents);
const returned = connection();
await returned.auth.signIn.email({ email: demoAccounts[0].email, password: demoPassword });
assert.ok((await returned.orders.list()).data.some((row) => row.number === placed.number));
passed('shared shopper bag, simulated checkout and persistence across a new login');
await Promise.all([shopper.auth.signOut(), admin.auth.signOut(), returned.auth.signOut()]);
await fetch(origin + '/auth/v1/sign-out', { method: 'POST', headers: adminHeaders, body: '{}' });
